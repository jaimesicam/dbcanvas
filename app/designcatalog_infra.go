// infraCertTTL is the certificate lifetime pair several of these types share.
func infraCertTTL(when string) []catalogOption {
	return []catalogOption{
		{Field: "certTtlValue", Default: 365, When: when,
			Desc: "Lifetime of the Intranet-CA-signed certificate, in certTtlUnit units; 0 is 365 days."},
		{Field: "certTtlUnit", Values: []string{"minutes", "hours", "days"}, Default: "days", When: when,
			Desc: "Unit of certTtlValue."},
	}
}

// infraVMSize is the per-node sizing block of the VM-capable types.
var infraVMSize = []catalogOption{
	{Field: "cpus", Desc: "CPUs: the container --cpus limit on Docker (0 is unlimited), the VM's vCPUs on Vagrant (0 is the engine default)."},
	{Field: "memoryGb", Desc: "Memory in GiB: the container --memory limit on Docker (0 is unlimited), the VM's memory on Vagrant (0 is the engine default)."},
	{Field: "deviceReadMbps", Desc: "Disk read limit in MB/s (container --device-read-bps); 0 is unlimited. Docker backend only."},
	{Field: "deviceWriteMbps", Desc: "Disk write limit in MB/s (container --device-write-bps); 0 is unlimited. Docker backend only."},
	{Field: "devicePath", When: "deviceReadMbps or deviceWriteMbps is set",
		Desc: "Host block device the disk limits apply to; \"\" auto-detects the disk backing Docker's data root."},
}

var infraUseProxy = catalogOption{Field: "useProxy", Desc: "Send package and file downloads through the Intranet's Squid proxy."}

func infraJoin(parts ...[]catalogOption) []catalogOption {
	var out []catalogOption
	for _, p := range parts {
		out = append(out, p...)
	}
	return out
}

